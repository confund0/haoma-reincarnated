    @Test fun theDeliveryLadderAgreesWithTheDaemon() {
        val tbl = JSONObject(corpusFile("delivery-ladder.json"))
        val states = tbl.getJSONArray("states").toStringList()
        assertTrue("the ladder table names no states — this test read nothing", states.isNotEmpty())

        val ranks = tbl.getJSONArray("rank")
        assertEquals("the ladder table's rank list does not line up with its state list", states.size, ranks.length())
        for (i in states.indices) {
            val daemon: Int? = if (ranks.isNull(i)) null else ranks.getInt(i)
            assertEquals(
                "rank(${states[i].display()}): the daemon says $daemon, this client says " +
                    "${DeliveryState.rank(states[i])}. The daemon is authoritative — " +
                    "frontend/internal/events/delivery_rank.go.",
                daemon,
                DeliveryState.rank(states[i]),
            )
        }

        checkMatrix(tbl, states, "outranks") { cur, next -> DeliveryState.outranks(cur, next) }
        checkMatrix(tbl, states, "advances") { cur, next -> DeliveryState.advances(cur, next) }
    }

    private fun checkMatrix(
        tbl: JSONObject,
        states: List<String>,
        key: String,
        answer: (String, String) -> Boolean,
    ) {
        val rows = tbl.getJSONArray(key)
        assertEquals("the ladder table's $key matrix does not line up with its state list", states.size, rows.length())
        for (i in states.indices) {
            val row = rows.getJSONArray(i)
            assertEquals("$key row ${states[i].display()} is the wrong width", states.size, row.length())
            for (j in states.indices) {
                val daemon = row.getBoolean(j)
                assertEquals(
                    "$key(cur=${states[i].display()}, next=${states[j].display()}): " +
                        "the daemon says $daemon, this client says ${answer(states[i], states[j])}. " +
                        "The daemon is authoritative — frontend/internal/events/delivery_rank.go.",
                    daemon,
                    answer(states[i], states[j]),
                )
            }
        }
    }

    
    @Test fun everySeededSiblingStateIsOneThisClientRecognises() {
        val tbl = JSONObject(corpusFile("delivery-ladder.json"))
        val states = tbl.getJSONArray("states").toStringList()
        val seeded = tbl.getJSONArray("seed_from_sibling").toStringList()
        assertEquals(states.size, seeded.size)
