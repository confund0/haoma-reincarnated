                seeded[i] in recognised,
            )
        }
        assertEquals(
            "the daemon's sibling floor is not the step this client's constants name",
            DeliveryState.SENT,
            tbl.getString("sibling_floor"),
        )
    }

    
    @Test fun aLateOutboxReportDoesNotStepTheMarkerBackward() {
        val row = timelineEvent("timeline-event.text-outbound-read")
        val push = deliveryStatus("delivery-state-changed.sent")
        assertEquals(
            "the corpus and the push do not name the same envelope, so this test would " +
                "have asserted on a row the push never reached",
            row.envelopeId,
            push.envelopeId,
        )

        var cache = TimelineCache(chatId = row.chatId)
        cache = mergeTimelineEvent(cache, row)
        cache = applyDeliveryStatus(cache, push.envelopeId, push.state)

        assertEquals(
            "the daemon holds this row at \"${row.deliveryState}\" and reported " +
                "\"${push.state}\" from its outbox; the marker moved anyway",
            row.deliveryState,
            cache.events[0].deliveryState,
        )
    }

    
    @Test fun anOutboxFailureLandsOnARowTheDaemonHoldsAtTheSiblingFloor() {
        val row = timelineEvent("timeline-event.text-outbound-mirrored")
        val failed = timelineEvent("timeline-event.text-outbound-failed")
        assertEquals(
            "the mirrored fixture is not at the sibling floor, so this test checks nothing",
            DeliveryState.SENT,
            row.deliveryState,
        )

        var cache = TimelineCache(chatId = row.chatId)
        cache = mergeTimelineEvent(cache, row)
        cache = applyDeliveryStatus(cache, row.envelopeId, failed.deliveryState)

        
        assertEquals(DeliveryState.SENT, cache.events[0].deliveryState)
        cache = mergeTimelineEvent(cache, row.copy(deliveryState = failed.deliveryState))
        assertEquals(
            "the daemon says this row is \"${failed.deliveryState}\" and this client still renders " +
                "\"${cache.events[0].deliveryState}\"",
            failed.deliveryState,
            cache.events[0].deliveryState,
        )
    }

    
