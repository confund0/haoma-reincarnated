    private fun corpusFile(name: String): String {
        val path = "/$CORPUS_DIR/$name"
        val stream = javaClass.getResourceAsStream(path)
            ?: throw AssertionError(
                "the corpus file $path is not on the test classpath. " +
                    "It is committed under app/src/test/resources/$CORPUS_DIR " +
                    "and generated by frontend/cmd/haoma/wirecorpus_test.go"
            )
        return stream.bufferedReader().use { it.readText() }
    }

    private fun manifest(): JSONObject = JSONObject(corpusFile("manifest.json"))

    
    private fun manifestFrames(): List<ManifestEntry> {
        val arr = manifest().getJSONArray("frames")
        assertTrue("the manifest names no frames — this test read nothing", arr.length() > 0)
        return (0 until arr.length()).map { i ->
            val o = arr.getJSONObject(i)
            ManifestEntry(
                name = o.getString("name"),
                file = o.getString("file"),
                type = o.getString("type"),
            )
        }
    }

    private data class ManifestEntry(val name: String, val file: String, val type: String)

    
    private fun frameOf(entry: ManifestEntry): Frame = Frame.decode(corpusFile(entry.file))

    
    private fun eventJson(frame: Frame): JSONObject =
        frame.payload!!.getJSONObject("event")

    
    private fun timelineFixtures(): Map<String, JSONObject> =
        manifestFrames()
            .filter { it.type == FrameType.TimelineEvent }
            .associate { it.name to eventJson(frameOf(it)) }

    
    @Test fun everyCommittedFrameDecodes() {
        val entries = manifestFrames()
        assertTrue("the corpus names no frames", entries.isNotEmpty())
        for (entry in entries) {
            val frame = frameOf(entry)
            assertEquals(
                "${entry.file}: the daemon stamped type \"${entry.type}\"; this client decoded \"${frame.type}\"",
                entry.type,
                frame.type,
            )
            assertTrue(
                "${entry.file}: the daemon shipped a payload and this client decoded none",
                frame.payload != null,
            )
        }
    }

    
    @Test fun everyWireTypeIsEitherConsumedOrNamedAsNotConsumed() {
        val known = knownFrameTypes()
        for (entry in manifestFrames()) {
            if (entry.type in known) continue
            if (entry.type in FRAME_TYPES_THIS_CLIENT_DOES_NOT_CONSUME) continue
            fail(
                "the daemon sends \"${entry.type}\" (fixture ${entry.name}) and this client has no " +
                    "FrameType constant for it. Either add the constant and a consumer, or name it in " +
                    "FRAME_TYPES_THIS_CLIENT_DOES_NOT_CONSUME with the reason."
            )
        }
    }

    private fun knownFrameTypes(): Set<String> =
        FrameType::class.java.declaredFields
            .filter { it.type == String::class.java }
            .mapNotNull {
                it.isAccessible = true
                it.get(FrameType) as? String
            }
            .toSet()

    
    @Test fun theParserReadsEveryFieldItClaimsToRead() {
        val fixtures = timelineFixtures()
        assertTrue("no timeline-event fixtures in the corpus", fixtures.isNotEmpty())

        val exercised = mutableSetOf<String>()
        for ((name, raw) in fixtures) {
            val parsed = TimelineEvent.fromJson(raw)
            for ((wireKey, field) in EVENT_FIELDS_READ) {
                if (!raw.has(wireKey)) continue
                exercised += wireKey
                assertEquals(
                    "$name: the daemon wrote \"$wireKey\"; this client's ${field.property} disagrees. " +
                        "The daemon is authoritative.",
                    field.fromWire(raw, wireKey),
                    field.fromParsed(parsed),
                )
            }
        }

        
        val idle = EVENT_FIELDS_READ.keys - exercised
        assertTrue(
            "no committed fixture carries $idle, so the mapping for those fields was never checked. " +
                "Either the daemon stopped sending them or the corpus needs a fixture that does.",
            idle.isEmpty(),
        )
    }

    
    @Test fun everyFieldTheDaemonSendsIsAccountedFor() {
        val seen = sortedSetOf<String>()
        for (raw in timelineFixtures().values) {
            seen += raw.keys().asSequence().toList()
        }
        assertTrue("no event keys found in the corpus — this test read nothing", seen.isNotEmpty())

        val accounted = EVENT_FIELDS_READ.keys + EVENT_FIELDS_NOT_READ.keys
        val unaccounted = seen - accounted
        assertTrue(
            "the daemon sends $unaccounted on an event row and this client neither reads them nor " +
                "names them as dropped. A field nobody decided about is a field that quietly does " +
                "nothing. Add it to EVENT_FIELDS_READ with a parsed property, or to " +
                "EVENT_FIELDS_NOT_READ with the reason it is dropped.",
            unaccounted.isEmpty(),
        )

        
        val stale = EVENT_FIELDS_NOT_READ.keys - seen
        assertTrue(
            "$stale are named as fields this client drops, but no committed fixture carries them. " +
                "Either the daemon stopped sending them, or the corpus lost the fixture that did.",
            stale.isEmpty(),
        )
    }

    
